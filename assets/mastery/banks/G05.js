  // Draw a simple organisational chart: rows[i] boxes on level i; each box links to a box on the level above.
  function orgChart(rows) {
    var W = 360, top = 18, gap = 46, bh = 18, H = top + rows.length * gap;
    var pos = rows.map(function (n, lv) {
      var bw = Math.min(46, Math.floor((W - 20) / n) - 6), y = top + lv * gap, out = [];
      for (var i = 0; i < n; i++) { var cx = 10 + (W - 20) * (i + 0.5) / n; out.push({ x: cx, y: y, w: bw }); }
      return out;
    });
    var s = '<svg viewBox="0 0 ' + W + ' ' + H + '" role="img" aria-label="Organisational chart with ' + rows.length + ' levels" xmlns="http://www.w3.org/2000/svg">';
    for (var lv = 1; lv < rows.length; lv++) {
      pos[lv].forEach(function (b, i) {
        var p = pos[lv - 1][Math.floor(i * rows[lv - 1] / rows[lv])];
        s += '<line x1="' + p.x.toFixed(1) + '" y1="' + (p.y + bh) + '" x2="' + b.x.toFixed(1) + '" y2="' + b.y + '" stroke="#9aa5b8" stroke-width="1.5"/>';
      });
    }
    pos.forEach(function (row, lv) {
      row.forEach(function (b) {
        s += '<rect x="' + (b.x - b.w / 2).toFixed(1) + '" y="' + b.y + '" width="' + b.w + '" height="' + bh + '" rx="3" fill="' + (lv === 0 ? '#195d9b' : '#ffffff') + '" stroke="#303a4c" stroke-width="1.2"/>';
      });
    });
    s += '<text x="' + (W / 2) + '" y="' + (top - 5) + '" font-size="10" text-anchor="middle" fill="#303a4c">Owner</text>';
    return s + '</svg>';
  }

